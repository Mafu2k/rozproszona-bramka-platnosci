#!/bin/bash
sqlplus -s / as sysdba <<EOF
WHENEVER SQLERROR EXIT FAILURE
WHENEVER OSERROR EXIT FAILURE
SET DEFINE OFF
ALTER SYSTEM SET job_queue_processes = 10 SCOPE = BOTH;
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE USER IF NOT EXISTS bramka IDENTIFIED BY "${BRAMKA_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER, CREATE SYNONYM, CREATE MATERIALIZED VIEW, CREATE DATABASE LINK, CREATE JOB TO bramka;
GRANT SELECT ON sys.dba_2pc_pending TO bramka;
GRANT SELECT ON sys.dba_2pc_neighbors TO bramka;
CREATE USER IF NOT EXISTS wezel_link IDENTIFIED BY "${LINK_PASSWORD}";
GRANT CREATE SESSION TO wezel_link;
EXIT
EOF
