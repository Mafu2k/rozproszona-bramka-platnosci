CREATE TABLE IF NOT EXISTS siec_kartowa (
    id_sieci  NUMBER(2)    CONSTRAINT siec_kartowa_pk PRIMARY KEY,
    kod       VARCHAR2(10) NOT NULL CONSTRAINT siec_kartowa_kod_uk UNIQUE,
    nazwa     VARCHAR2(50) NOT NULL,
    nr_wezla  NUMBER(2)    NOT NULL CONSTRAINT siec_kartowa_wezel_uk UNIQUE,
    CONSTRAINT siec_kartowa_wezel_ck CHECK (nr_wezla = id_sieci)
);

CREATE TABLE IF NOT EXISTS zakres_bin (
    id_zakresu  NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT zakres_bin_pk PRIMARY KEY,
    id_sieci    NUMBER(2) NOT NULL CONSTRAINT zakres_bin_siec_fk REFERENCES siec_kartowa (id_sieci),
    bin_od      NUMBER(8) NOT NULL,
    bin_do      NUMBER(8) NOT NULL,
    dlugosc_pan NUMBER(2) DEFAULT 16 NOT NULL,
    CONSTRAINT zakres_bin_zakres_ck CHECK (bin_od BETWEEN 10000000 AND 99999999 AND bin_do BETWEEN bin_od AND 99999999),
    CONSTRAINT zakres_bin_dlugosc_ck CHECK (dlugosc_pan BETWEEN 12 AND 19)
);

CREATE TABLE IF NOT EXISTS klient (
    id_klienta       NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT klient_pk PRIMARY KEY,
    imie             VARCHAR2(50)  NOT NULL,
    nazwisko         VARCHAR2(80)  NOT NULL,
    email            VARCHAR2(120) NOT NULL CONSTRAINT klient_email_uk UNIQUE,
    telefon          VARCHAR2(20),
    kraj             CHAR(2)       DEFAULT 'PL' NOT NULL,
    data_rejestracji TIMESTAMP(3)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    status           VARCHAR2(12)  DEFAULT 'AKTYWNY' NOT NULL
        CONSTRAINT klient_status_ck CHECK (status IN ('AKTYWNY', 'ZABLOKOWANY', 'USUNIETY'))
);

CREATE TABLE IF NOT EXISTS sklep (
    id_sklepu        NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT sklep_pk PRIMARY KEY,
    nazwa            VARCHAR2(100) NOT NULL,
    nip              CHAR(10)      NOT NULL CONSTRAINT sklep_nip_uk UNIQUE,
    kategoria_mcc    CHAR(4)       NOT NULL,
    url              VARCHAR2(200),
    email_kontaktowy VARCHAR2(120) NOT NULL,
    status           VARCHAR2(12)  DEFAULT 'AKTYWNY' NOT NULL
        CONSTRAINT sklep_status_ck CHECK (status IN ('AKTYWNY', 'ZAWIESZONY', 'USUNIETY')),
    hash_klucza_api  CHAR(64)      CONSTRAINT sklep_klucz_api_uk UNIQUE
);

CREATE TABLE IF NOT EXISTS uzytkownik (
    id_uzytkownika NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT uzytkownik_pk PRIMARY KEY,
    login          VARCHAR2(50)  NOT NULL CONSTRAINT uzytkownik_login_uk UNIQUE,
    hash_hasla     VARCHAR2(100) NOT NULL,
    rola           VARCHAR2(10)  NOT NULL CONSTRAINT uzytkownik_rola_ck CHECK (rola IN ('ADMIN', 'OPERATOR')),
    id_sieci       NUMBER(2)     CONSTRAINT uzytkownik_siec_fk REFERENCES siec_kartowa (id_sieci),
    status         VARCHAR2(12)  DEFAULT 'AKTYWNY' NOT NULL
        CONSTRAINT uzytkownik_status_ck CHECK (status IN ('AKTYWNY', 'ZABLOKOWANY')),
    CONSTRAINT uzytkownik_rola_siec_ck CHECK (
        (rola = 'ADMIN' AND id_sieci IS NULL) OR (rola = 'OPERATOR' AND id_sieci IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS klient_nazwisko_ix ON klient (UPPER(nazwisko));
CREATE INDEX IF NOT EXISTS zakres_bin_siec_ix ON zakres_bin (id_sieci);
CREATE INDEX IF NOT EXISTS uzytkownik_siec_ix ON uzytkownik (id_sieci);

CREATE OR REPLACE TRIGGER zakres_bin_rozlacznosc_trg
AFTER INSERT OR UPDATE OF bin_od, bin_do ON zakres_bin
DECLARE
    v_kolizje NUMBER;
BEGIN
    LOCK TABLE zakres_bin IN EXCLUSIVE MODE;
    SELECT COUNT(*)
      INTO v_kolizje
      FROM zakres_bin a
      JOIN zakres_bin b
        ON a.id_zakresu < b.id_zakresu
       AND a.bin_od <= b.bin_do
       AND b.bin_od <= a.bin_do;
    IF v_kolizje > 0 THEN
        RAISE_APPLICATION_ERROR(-20050, 'Zakresy BIN nie mogą się nakładać');
    END IF;
END;
