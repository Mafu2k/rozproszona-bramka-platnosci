DECLARE
    PROCEDURE utworz_log(p_tabela IN VARCHAR2) IS
        v_istnieje NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_istnieje FROM user_mview_logs WHERE master = p_tabela;
        IF v_istnieje = 0 THEN
            EXECUTE IMMEDIATE 'CREATE MATERIALIZED VIEW LOG ON ' || p_tabela || ' WITH PRIMARY KEY';
        END IF;
    END utworz_log;
BEGIN
    utworz_log('SIEC_KARTOWA');
    utworz_log('ZAKRES_BIN');
    utworz_log('KLIENT');
    utworz_log('SKLEP');
    utworz_log('UZYTKOWNIK');
END;
/

