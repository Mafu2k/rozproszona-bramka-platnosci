MERGE INTO siec_kartowa d
USING (
    SELECT 1 AS id_sieci, 'VISA' AS kod, 'Visa' AS nazwa, 1 AS nr_wezla FROM dual UNION ALL
    SELECT 2, 'MC', 'MasterCard', 2 FROM dual UNION ALL
    SELECT 3, 'AMEX', 'American Express', 3 FROM dual
) s
ON (d.id_sieci = s.id_sieci)
WHEN NOT MATCHED THEN
    INSERT (id_sieci, kod, nazwa, nr_wezla) VALUES (s.id_sieci, s.kod, s.nazwa, s.nr_wezla);

MERGE INTO zakres_bin d
USING (
    SELECT 1 AS id_sieci, 40000000 AS bin_od, 49999999 AS bin_do, 16 AS dlugosc_pan FROM dual UNION ALL
    SELECT 2, 51000000, 55999999, 16 FROM dual UNION ALL
    SELECT 2, 22210000, 27209999, 16 FROM dual UNION ALL
    SELECT 3, 34000000, 34999999, 15 FROM dual UNION ALL
    SELECT 3, 37000000, 37999999, 15 FROM dual
) s
ON (d.bin_od = s.bin_od)
WHEN NOT MATCHED THEN
    INSERT (id_sieci, bin_od, bin_do, dlugosc_pan) VALUES (s.id_sieci, s.bin_od, s.bin_do, s.dlugosc_pan);

COMMIT;
