#!/bin/bash
sqlplus -s / as sysdba <<EOF
WHENEVER SQLERROR EXIT FAILURE
WHENEVER OSERROR EXIT FAILURE
SET DEFINE OFF
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE USER bramka IDENTIFIED BY "${BRAMKA_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER, CREATE SYNONYM, CREATE MATERIALIZED VIEW, CREATE DATABASE LINK TO bramka;
EXIT
EOF
